-- Hernoemen: nieuw model met nette naam, gegevens van het oude model.
insert into public.cars (id, brand, model, year_from, year_to, body, fuels, source)
select distinct on (s.doel) s.doel, split_part(s.doel, '|', 1), substr(s.doel, strpos(s.doel, '|') + 1),
       min(c.year_from) over (partition by s.doel), max(c.year_to) over (partition by s.doel), c.body, c.fuels, 'rdw'
from samen s join public.cars c on c.id = s.oud
where s.hernoem
on conflict (id) do nothing;

-- Verwijzingen omzetten (check-ins, garage, foto's, kentekens) en daarna de oude modellen verwijderen.
update public.reviews r set car_id = s.doel from samen s where r.car_id = s.oud and s.doel is not null;
update public.garage_items g set car_id = s.doel from samen s where g.car_id = s.oud and s.doel is not null;
update public.photo_submissions p set car_id = s.doel from samen s where p.car_id = s.oud and s.doel is not null;
update public.plate_uses p set car_id = s.doel from samen s where p.car_id = s.oud and s.doel is not null;
update public.rdw_models m set car_id = s.doel, match = 'zeker', updated_at = now() from samen s where m.car_id = s.oud;
delete from public.cars c using samen s
where c.id = s.oud and c.source = 'rdw'
  and not exists (select 1 from public.reviews r where r.car_id = c.id)
  and not exists (select 1 from public.garage_items g where g.car_id = c.id)
  and not exists (select 1 from public.photo_submissions p where p.car_id = c.id);
